const BLS = new Set(['BLS', 'EMT-B', 'AIDE', 'PROBATIONARY'])
const ALS = new Set([
  'AEMT',
  'EMT-CC',
  'EMT-I',
  'PARAMEDIC',
  'PARAMEDIC-CC',
  'NURSE',
  'DOCTOR',
  'MEDICAL DIRECTOR',
])

export function profileIsBls(user) {
  const cert = String(user?.certification || '').trim().toUpperCase()
  if (ALS.has(cert)) return false
  if (BLS.has(cert)) return true
  if (user?.isBls === true || user?.bls === true) return true
  if (user?.isBls === false || user?.bls === false) return false
  return false
}
